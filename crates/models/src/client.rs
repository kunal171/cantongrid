//! Deterministic client contracts for model APIs; financial values never become JS numbers.
use crate::{Catalog, FieldType, Model, ModelError};

impl Model {
    /// Fingerprints avoid collisions across namespaces, revisions and overlapping model names.
    pub fn api_name(&self) -> Result<String, ModelError> {
        Ok(format!(
            "model_{}_{}",
            self.name,
            &self.fingerprint()?[..16]
        ))
    }
    /// GraphQL and TypeScript use the same safe generated type stem.
    pub fn api_type(&self) -> Result<String, ModelError> {
        Ok(format!("Model_{}", &self.fingerprint()?[..16]))
    }
}

impl Catalog {
    /// Emit schema definitions from validated declarations, without opening a database or ledger.
    pub fn graphql_schema(&self) -> Result<String, ModelError> {
        let mut result = String::from(
            "# Exact Int64/Numeric values are strings. Access requires current source and caller grants.\n",
        );
        let mut root = String::from("type Query {\n");
        for model in self.models() {
            let stem = model.api_type()?;
            result.push_str(&format!("type {stem}Values {{\n"));
            for (name, expression) in &model.fields {
                result.push_str(&format!(
                    "  {name}: {}\n",
                    graphql_type(&expression.output_type()?)
                ));
            }
            result.push_str(&format!("}}\ntype {stem}Row {{ contractId: String!, values: {stem}Values! }}\ntype {stem}Page {{ items: [{stem}Row!]!, visibleTotal: String!, nextCursor: String, fingerprint: String! }}\n"));
            root.push_str(&format!(
                "  {}(namespace: String!, limit: Int, cursor: String): {stem}Page!\n",
                model.api_name()?
            ));
        }
        result.push_str(&format!("{root}}}\n"));
        Ok(result)
    }

    /// Generate transport interfaces only, not a Daml Ledger SDK or runtime value validator.
    pub fn typescript(&self) -> Result<String, ModelError> {
        let mut result = String::from(
            "// Generated by CantonGrid. Int64 and Numeric are exact decimal strings.\n// These describe indexed API rows, not Ledger commands or authorization grants.\n",
        );
        for model in self.models() {
            let stem = model.api_type()?;
            result.push_str(&format!("export interface {stem}Values {{\n"));
            for (name, expression) in &model.fields {
                result.push_str(&format!(
                    "  readonly {name}: {};\n",
                    typescript_type(&expression.output_type()?)
                ));
            }
            result.push_str(&format!("}}\nexport interface {stem}Row {{ readonly contractId: string; readonly values: {stem}Values; }}\nexport interface {stem}Page {{ readonly items: readonly {stem}Row[]; readonly visibleTotal: string; readonly nextCursor: string | null; readonly fingerprint: string; }}\nexport const {} = {{ field: \"{}\", fingerprint: \"{}\" }} as const;\n", model.api_name()?, model.api_name()?, model.fingerprint()?));
        }
        Ok(result)
    }
}

/// Nullable fields remain nullable; GraphQL Int/Float cannot represent our financial domain.
fn graphql_type(kind: &FieldType) -> String {
    match kind {
        FieldType::Optional { item } => graphql_type(item).trim_end_matches('!').to_owned(),
        FieldType::Bool => "Boolean!".into(),
        _ => "String!".into(),
    }
}
fn typescript_type(kind: &FieldType) -> String {
    match kind {
        FieldType::Optional { item } => format!("{} | null", typescript_type(item)),
        FieldType::Bool => "boolean".into(),
        _ => "string".into(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn client_contracts_keep_exact_values_nullability_and_revision_identity() {
        let text = include_str!("../assets/poc/models.json");
        let catalog = Catalog::parse(text).unwrap();
        let ts = catalog.typescript().unwrap();
        let gql = catalog.graphql_schema().unwrap();
        assert!(ts.contains("readonly quantityLot: string;"));
        assert!(ts.contains("readonly outcome: boolean | null;"));
        assert!(gql.contains("quantityLot: String!"));
        assert!(gql.contains("outcome: Boolean\n"));
        assert!(!gql.contains("Float"));
        let changed = Catalog::parse(&text.replace("\"revision\": 1", "\"revision\": 2")).unwrap();
        assert_ne!(
            catalog.models()[0].api_name().unwrap(),
            changed.models()[0].api_name().unwrap()
        );
    }
}
